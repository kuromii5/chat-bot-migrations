-- +migrate Up

CREATE SCHEMA IF NOT EXISTS core AUTHORIZATION ${ADMIN_USER};

GRANT USAGE ON SCHEMA core TO ${APP_USER}, ${READONLY_USER};

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA core TO ${APP_USER};
GRANT SELECT ON ALL TABLES IN SCHEMA core TO ${READONLY_USER};
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA core TO ${APP_USER};

ALTER DEFAULT PRIVILEGES FOR ROLE ${ADMIN_USER} IN SCHEMA core
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_USER};
ALTER DEFAULT PRIVILEGES FOR ROLE ${ADMIN_USER} IN SCHEMA core
  GRANT SELECT ON TABLES TO ${READONLY_USER};
ALTER DEFAULT PRIVILEGES FOR ROLE ${ADMIN_USER} IN SCHEMA core
  GRANT USAGE, SELECT ON SEQUENCES TO ${APP_USER};

-- +migrate Down

DROP SCHEMA IF EXISTS core;
